import 'dotenv/config';
import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import mongoose from 'mongoose';
import contentRoutes from './routes/content.js';
import leadRoutes from './routes/leads.js';
import applicationRoutes from './routes/applications.js';
import adminRoutes from './routes/admin.js';
const app = express();
const port = Number(process.env.PORT) || 5000;
const allowedOrigins = [...new Set(['http://localhost:5173', 'https://riyadvi-assesment.vercel.app', 'https://riyadvi.up.railway.app', ...(process.env.CLIENT_ORIGIN || '').split(',').map(s => s.trim()).filter(Boolean)])];
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({origin(origin,callback){if(!origin || allowedOrigins.includes(origin)) return callback(null,true);return callback(new Error('Origin is not allowed by CORS'));},methods:['GET','POST','DELETE','OPTIONS'],allowedHeaders:['Content-Type','x-admin-key']}));
app.use(express.json({limit:'30kb'}));
app.get('/api/health',(_req,res)=>res.status(200).json({status:'ok',database:mongoose.connection.readyState===1?'connected':'disconnected',timestamp:new Date().toISOString()}));
app.use('/api/content',contentRoutes);
app.use('/api/leads',leadRoutes);
app.use('/api/contact',leadRoutes);
app.use('/api/consultation',leadRoutes);
app.use('/api/health-checkup',leadRoutes);
app.use('/api/lead-magnet',leadRoutes);
app.use('/api/applications',applicationRoutes);
app.use('/api/admin',adminRoutes);
app.use((req,res)=>res.status(404).json({message:`Route not found: ${req.method} ${req.path}`}));
app.use((err,_req,res,_next)=>{console.error('[api-error]',err.message);if(err.message==='Origin is not allowed by CORS')return res.status(403).json({message:'Request origin is not allowed.'});return res.status(500).json({message:'Unexpected server error. Please try again.'});});
app.listen(port,()=>console.log(`Riyadvi API listening on port ${port}`));
if(process.env.MONGODB_URI){mongoose.connect(process.env.MONGODB_URI,{serverSelectionTimeoutMS:8000}).then(()=>console.log('MongoDB connected')).catch(err=>console.error('MongoDB connection failed:',err.message));}else{console.warn('MONGODB_URI is not configured. Content routes work; form submissions return 503 until MongoDB is configured.');}
